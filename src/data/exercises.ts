const split = <T extends string>(s: string): T[] =>
  s ? (s.split(",") as T[]) : [];
const originalExercises: Exercise[] = rows.map(
  ([
    id,
    name,
    primary,
    secondary,
    equipment,
    level,
    pattern,
    reps,
    steps,
    tip,
    seconds,
    unilateral,
  ]) => ({
    id,
    name,
    primary: split<Muscle>(primary),
    secondary: split<Muscle>(secondary),
    equipment: split<Equipment>(equipment),
    level,
    pattern,
    reps,
    rest: level === "advanced" ? 90 : 45,
    steps: steps.split("|"),
    tip,
    seconds,
    unilateral,
  }),
);
